from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import json, shutil
out=Path('/tmp/lyrica-web');out.mkdir(exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=shutil.which('chromium') or None,headless=True,args=['--no-sandbox'])
 context=browser.new_context(viewport={'width':1440,'height':1050},service_workers='block')
 page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.route('https://itunes.apple.com/**',lambda route:route.fulfill(json={'results':[{'kind':'song','trackId':123,'trackName':'A test song','artistName':'Test Artist','collectionName':'Test Album','trackTimeMillis':180000}]}))
 page.route('https://lrclib.net/api/**',lambda route:route.fulfill(json={'id':1,'trackName':'A test song','artistName':'Test Artist','albumName':'Test Album','duration':180,'instrumental':False,'plainLyrics':'Hola mundo\n\nBuenos días'}))
 page.goto('http://127.0.0.1:4173');page.wait_for_load_state('networkidle')
 expect(page.get_by_role('heading',name='Find the words. Feel the meaning.')).to_be_visible()
 page.screenshot(path=str(out/'discover.png'),full_page=True)
 page.get_by_role('button',name='Open the bilingual demo').click()
 expect(page.get_by_text('I open the window to the day',exact=True)).to_be_visible()
 page.locator('.lyric-row').first.click();expect(page.locator('.lyric-row').first).to_have_attribute('aria-pressed','true')
 page.locator('#target-language').select_option('ar');expect(page.get_by_text('أفتح النافذة للنهار',exact=True)).to_be_visible()
 assert page.locator('.translated').first.get_attribute('dir')=='rtl'
 page.locator('#target-language').select_option('en')
 page.get_by_role('button',name='Save favorite',exact=True).click()
 page.get_by_role('button',name='Enable permitted offline storage').click()
 expect(page.locator('dialog')).not_to_be_visible()
 page.screenshot(path=str(out/'reader.png'),full_page=True)
 page.get_by_role('link',name='Your library').click();expect(page.get_by_text('Donde empieza el día',exact=True)).to_be_visible()
 page.reload();page.wait_for_load_state('networkidle');expect(page.get_by_text('Donde empieza el día',exact=True)).to_be_visible()
 page.locator('[data-nav=search]').click()
 page.get_by_role('searchbox').fill('Test Artist');page.get_by_role('button',name='Search',exact=True).click()
 page.get_by_role('button',name='A test song').click()
 expect(page.get_by_text('Hola mundo',exact=True)).to_be_visible()
 page.get_by_role('button',name='Paste a translation',exact=True).click()
 page.locator('#manual-text').fill('Hello world\nGood morning')
 page.get_by_role('button',name='Use translation',exact=True).click()
 expect(page.get_by_text('Hello world',exact=True)).to_be_visible()
 page.locator('[data-nav=settings]').click()
 page.locator('#theme').select_option('dark')
 expect(page.locator('html')).to_have_attribute('data-theme','dark')
 page.locator('#cache').uncheck()
 page.get_by_role('link',name='Your library').click()
 assert page.locator('.song-duration',has_text='Saved').count()==0
 page.set_viewport_size({'width':390,'height':844})
 page.locator('[data-nav=search]').click()
 page.get_by_role('searchbox').fill('');page.get_by_role('button',name='Search',exact=True).click()
 page.get_by_role('button',name='Open the bilingual demo').click()
 expect(page.get_by_text('I open the window to the day',exact=True)).to_be_visible()
 page.screenshot(path=str(out/'mobile.png'),full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile overflow'
 assert not errors,errors
 print('Browser checks passed: search, LRCLIB, paired highlights, Arabic RTL, language switching, favorite opt-in, reload persistence, manual translation, cache clearing, dark appearance, mobile layout.')
 offline=browser.new_context(service_workers='allow')
 shell=offline.new_page();shell.goto('http://127.0.0.1:4173');shell.wait_for_load_state('networkidle')
 shell.evaluate('navigator.serviceWorker.ready')
 shell.reload();shell.wait_for_load_state('networkidle')
 offline.set_offline(True);shell.reload();shell.wait_for_load_state('networkidle')
 expect(shell.get_by_role('button',name='Open the bilingual demo')).to_be_visible()
 print('Service-worker application shell verified offline.')
 browser.close()
